  const detectInitialLang = () => {
    const saved = localStorage.getItem("neoguard_lang");
    if (saved && TRANSLATIONS[saved]) return saved;
    const nav = (navigator.language || "en").slice(0, 2).toLowerCase();
    return TRANSLATIONS[nav] ? nav : "en";
  };

  let currentLang = detectInitialLang();

  window.neoI18n = {
    getLang: () => currentLang,
    t: (key, vars = {}) => {
      const dict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
      let str = dict[key] ?? TRANSLATIONS.en[key] ?? key;
      for (const [k, v] of Object.entries(vars)) {
        str = str.replaceAll(`{${k}}`, String(v));
      }
      return str;
    },
    setLang: (lang) => {
      if (!TRANSLATIONS[lang]) return;
      currentLang = lang;
      localStorage.setItem("neoguard_lang", lang);
      document.documentElement.lang = lang;
      window.neoI18n.apply();
    },
    apply: () => {
      document.title = window.neoI18n.t("page_title");
      document.querySelectorAll("[data-i18n]").forEach((el) => {
        const key = el.getAttribute("data-i18n");
        if (key) el.textContent = window.neoI18n.t(key);
      });
      document.querySelectorAll("[data-i18n-title]").forEach((el) => {
        const key = el.getAttribute("data-i18n-title");
        if (key) el.title = window.neoI18n.t(key);
      });
      document.querySelectorAll("#langSelectTop, #langSelectLogin").forEach((sel) => {
        if (sel) sel.value = currentLang;
      });
    },
  };
